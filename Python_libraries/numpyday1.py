import numpy as np

marks = np.array([75,80,85,90,55])

# Numpy Methods 

# Sum
print("Sum:",np.sum(marks))

# Mean
print("Mean:",np.mean(marks))

# Max
print("Max:",np.max(marks))

# Minimun
print("Min:",np.min(marks))

# sort
print("Sort:",np.sort(marks))

# average
print("Average:",np.average(marks))

